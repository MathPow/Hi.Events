import {t} from "@lingui/macro";
import {ActionIcon, Button, Table as MantineTable, UnstyledButton} from '@mantine/core';
import {IdParam} from "../../../types.ts";
import {IconChartBar, IconCopy, IconDotsVertical, IconLink, IconPencil, IconPlus, IconShare, IconTrash} from "@tabler/icons-react";
import {useClipboard, useDisclosure} from "@mantine/hooks";
import {useState} from "react";
import {NoResultsSplash} from "../NoResultsSplash";
import {EditAffiliateModal} from "../../modals/EditAffiliateModal";
import {ShareModal} from "../../modals/ShareModal";
import {useDeleteAffiliate} from "../../../mutations/useDeleteAffiliate";
import {showError, showSuccess} from "../../../utilites/notifications.tsx";
import {confirmationDialog} from "../../../utilites/confirmationDialog.tsx";
import {useParams} from "react-router";
import {Affiliate} from "../../../api/affiliate.client.ts";
import classes from "./AffiliateTable.module.scss";
import {Table, TableHead} from "../Table";
import {ActionMenu} from "../ActionMenu";
import {affiliatePartnerPageUrl, affiliateShareUrl} from "../../../utilites/urlHelper.ts";
import {useGetEvent} from "../../../queries/useGetEvent.ts";
import {useGetEventPromoCodes} from "../../../queries/useGetEventPromoCodes.ts";
import {getInitials} from "../../../utilites/helpers.ts";
import {formatCurrency} from "../../../utilites/currency.ts";
import {StatusTag} from "../StatusTag";

interface AffiliateTableProps {
    affiliates: Affiliate[];
    openCreateModal: () => void;
}

export const AffiliateTable = ({affiliates, openCreateModal}: AffiliateTableProps) => {
    const [editModalOpen, {open: openEditModal, close: closeEditModal}] = useDisclosure(false);
    const [shareModalOpen, {open: openShareModal, close: closeShareModal}] = useDisclosure(false);
    const [selectedAffiliateId, setSelectedAffiliateId] = useState<IdParam>();
    const [selectedAffiliate, setSelectedAffiliate] = useState<Affiliate>();
    const deleteMutation = useDeleteAffiliate();
    const {eventId} = useParams();
    const copy = useClipboard()
    const {data: event} = useGetEvent(eventId);
    const {data: promoCodes} = useGetEventPromoCodes(eventId, {perPage: 100});

    const shareUrl = (affiliate: Affiliate) => {
        const promoCode = promoCodes?.data?.find(code => code.id === affiliate.promo_code_id)?.code;
        return affiliateShareUrl(event!, affiliate.code, promoCode);
    };

    const handleDeleteAffiliate = (affiliateId: IdParam, eventId: IdParam) => {
        deleteMutation.mutate({affiliateId, eventId}, {
            onSuccess: () => {
                showSuccess(t`Affiliate deleted successfully`);
            },
            onError: (error: any) => {
                showError(error.message);
            }
        });
    }

    const copyToClipboard = (text: string) => {
        copy.copy(text)
        showSuccess(t`Copied to clipboard`);
    };

    if (affiliates.length === 0) {
        return (
            <NoResultsSplash
                heading={t`No Affiliates to show`}
                icon="partager"
                subHeading={(
                    <p>
                        {t`Affiliates help you track sales generated by partners and influencers. Create affiliate codes and share them to monitor performance.`}
                    </p>
                )}
            >
                <Button leftSection={<IconPlus size={20}/>} onClick={openCreateModal}>
                    {t`Create Affiliate`}
                </Button>
            </NoResultsSplash>
        );
    }

    return (
        <>
            <Table>
                <TableHead>
                    <MantineTable.Tr>
                        <MantineTable.Th>{t`Affiliate`}</MantineTable.Th>
                        <MantineTable.Th>{t`Code`}</MantineTable.Th>
                        <MantineTable.Th>{t`Status`}</MantineTable.Th>
                        <MantineTable.Th>{t`Sales`}</MantineTable.Th>
                        <MantineTable.Th>{t`Revenue`}</MantineTable.Th>
                        <MantineTable.Th/>
                    </MantineTable.Tr>
                </TableHead>
                <MantineTable.Tbody>
                    {affiliates.map((affiliate) => (
                        <MantineTable.Tr key={affiliate.id}>
                            <MantineTable.Td>
                                <div className={classes.affiliateInfo}>
                                    <span className={classes.avatar} aria-hidden>{getInitials(affiliate.name || '?')}</span>
                                    <span className={classes.affiliateText}>
                                        <span className={classes.affiliateName}>{affiliate.name}</span>
                                        {affiliate.email && (
                                            <span className={classes.affiliateEmail}>{affiliate.email}</span>
                                        )}
                                    </span>
                                </div>
                            </MantineTable.Td>
                            <MantineTable.Td>
                                <div className={classes.codeCell}>
                                    <span className={classes.codeText}>{affiliate.code}</span>
                                    <UnstyledButton
                                        className={classes.copyButton}
                                        onClick={() => copyToClipboard(shareUrl(affiliate))}
                                    >
                                        <IconLink size={15}/>
                                        {t`Copy URL`}
                                    </UnstyledButton>
                                </div>
                            </MantineTable.Td>
                            <MantineTable.Td>
                                <StatusTag tone={affiliate.status === 'ACTIVE' ? 'ok' : 'neutral'}>
                                    {affiliate.status === 'ACTIVE' ? t`Active` : t`Inactive`}
                                </StatusTag>
                            </MantineTable.Td>
                            <MantineTable.Td>
                                <span className={classes.figure}>{affiliate.total_sales}</span>
                            </MantineTable.Td>
                            <MantineTable.Td>
                                <span className={classes.figure}>
                                    {formatCurrency(affiliate.total_sales_gross, event?.currency)}
                                </span>
                            </MantineTable.Td>
                            <MantineTable.Td>
                                <ActionMenu
                                    target={(
                                        <ActionIcon className={classes.menuButton} variant="subtle"
                                                    aria-label={t`Actions`}>
                                            <IconDotsVertical size={20}/>
                                        </ActionIcon>
                                    )}
                                    itemsGroups={[
                                        {
                                            label: t`Actions`,
                                            items: [
                                                {
                                                    label: t`Edit Affiliate`,
                                                    icon: <IconPencil size={14}/>,
                                                    onClick: () => {
                                                        setSelectedAffiliateId(affiliate.id);
                                                        openEditModal();
                                                    }
                                                },
                                                {
                                                    label: t`Copy Code`,
                                                    icon: <IconCopy size={14}/>,
                                                    onClick: () => copyToClipboard(affiliate.code)
                                                },
                                                {
                                                    label: t`Copy Affiliate Link`,
                                                    icon: <IconCopy size={14}/>,
                                                    onClick: () => copyToClipboard(shareUrl(affiliate))
                                                },
                                                {
                                                    label: t`Copy Partner Page Link`,
                                                    icon: <IconChartBar size={14}/>,
                                                    visible: !!affiliate.public_token,
                                                    onClick: () => copyToClipboard(affiliatePartnerPageUrl(affiliate.public_token!))
                                                },
                                                {
                                                    label: t`Share Affiliate Link`,
                                                    icon: <IconShare size={14}/>,
                                                    onClick: () => {
                                                        setSelectedAffiliate(affiliate);
                                                        openShareModal();
                                                    }
                                                },
                                                {
                                                    label: t`Delete Affiliate`,
                                                    icon: <IconTrash size={14}/>,
                                                    color: "red",
                                                    onClick: () => confirmationDialog(
                                                        t`Are you sure you want to delete this affiliate? This action cannot be undone.`,
                                                        () => handleDeleteAffiliate(affiliate.id, eventId!)
                                                    )
                                                }
                                            ]
                                        }
                                    ]}
                                />
                            </MantineTable.Td>
                        </MantineTable.Tr>
                    ))}
                </MantineTable.Tbody>
            </Table>

            {editModalOpen && selectedAffiliateId && (
                <EditAffiliateModal
                    affiliateId={selectedAffiliateId}
                    onClose={closeEditModal}
                />
            )}

            {shareModalOpen && selectedAffiliate && event && (
                <ShareModal
                    opened={shareModalOpen}
                    onClose={closeShareModal}
                    url={shareUrl(selectedAffiliate)}
                    title={event.title}
                    modalTitle={t`Share Affiliate Link`}
                    shareText={t`Here is your affiliate link`}
                />
            )}
        </>
    );
};
